/**
 * Static, immutable catalog (RNF-04). It carries no availability: that is mutable
 * state and lives in `availability.ts`, the separate structure the same
 * requirement demands.
 *
 * Hours, closures, exceptions and fees are transcribed from the legacy console
 * implementation; prices, fees and rates are written in cents. Five museum texts
 * differ from it because they contradicted its own rules (DT5).
 */
