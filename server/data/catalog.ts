function span(openHour: number, openMinute: number, closeHour: number, closeMinute: number): OpeningHours {
  return {
    open: { hour: openHour, minute: openMinute },
    close: { hour: closeHour, minute: closeMinute },
  }
}

/** The price is written in cents: 35 euros is 3500. */
function section(name: string, priceInCents: number): TheaterSection {
  return { name, price: cents(priceInCents) }
}

/** The price is written in cents, as in `section`. */
function format(id: CinemaFormatId, priceInCents: number, seats: number): CinemaFormat {
  return { id, price: cents(priceInCents), seats }
}

function film(title: string, classification: FilmClassification, durationMinutes: number): CinemaFilm {
  return { title, classification, durationMinutes }
}

function closure(day: number, month: number, name: string): AnnualClosure {
  return { day, month, name }
}

